package tech.justdev.pitest

import org.pitest.mutationtest.build.InterceptorParameters
import org.pitest.mutationtest.build.MutationInterceptor
import org.pitest.mutationtest.build.MutationInterceptorFactory
import org.pitest.plugin.Feature
import org.pitest.plugin.FeatureParameter
import java.nio.file.Path

class CoprogoEquivalentKotlinMutationFilterFactory : MutationInterceptorFactory {
    override fun description(): String = "Filters verified equivalent mutations generated by Kotlin inline collection functions"

    override fun createInterceptor(parameters: InterceptorParameters): MutationInterceptor =
        CoprogoEquivalentKotlinMutationFilter(
            EquivalentMutationWhitelist.load(
                Path.of(
                    parameters
                        .getString(WHITELIST_PARAMETER)
                        .orElseThrow { IllegalArgumentException("Missing equivalent-mutation whitelist path") },
                ),
            ),
        )

    override fun provides(): Feature =
        Feature
            .named("FCOPROGO_KOTLIN_EQUIVALENT")
            .withDescription(description())
            .withParameter(WHITELIST_PARAMETER)
            .withOnByDefault(false)

    private companion object {
        val WHITELIST_PARAMETER: FeatureParameter =
            FeatureParameter
                .named("whitelist")
                .withDescription("Path to the JSON file containing verified equivalent mutations")
    }
}
